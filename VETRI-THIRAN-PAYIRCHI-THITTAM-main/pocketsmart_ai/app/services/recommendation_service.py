def make_recommendation(planner_type: str, payload: dict[str, Any], image_path: str | None = None):
    catalog = get_budgeted_catalog(planner_type, float(payload["budget"]))
    ai_data, ai_used = generate_recommendation(planner_type, payload, catalog, image_path)
    if ai_data:
        # Sanitize AI output against the candidate catalog and budget.
        allowed = {(x["name"], x["platform"]): x for x in catalog}
        clean = []
        remaining = float(payload["budget"])
        for item in ai_data.get("recommendations", []):
            key = (item.get("name"), item.get("platform"))
            source = allowed.get(key)
            if not source or source["price"] > remaining:
                continue
            clean.append({**source, "reason": str(item.get("reason", "Budget-aware recommendation."))})
            remaining -= source["price"]
        ai_data["recommendations"] = clean
        ai_data["allocation"] = {str(k): float(v) for k, v in (ai_data.get("allocation") or {}).items()}
        ai_data["tips"] = [str(x) for x in (ai_data.get("tips") or [])][:6]
        ai_data["summary"] = str(ai_data.get("summary", "Budget-aware recommendations generated by Gemini."))
        return ai_data, True
    fallback = {"home": fallback_home, "party": fallback_party, "jewelry": fallback_jewelry}[planner_type](payload, catalog)
    return fallback, False
