from typing import Any
from .catalog_service import get_budgeted_catalog
from .gemini_utils import generate_recommendation


def _sum_prices(items):
    return sum(float(i.get("price", 0)) for i in items)


def fallback_home(payload: dict[str, Any], catalog: list[dict[str, Any]]):
    budget = float(payload["budget"])
    selected = []
    total = 0
    for item in catalog:
        if total + item["price"] <= budget * 0.92:
            selected.append({**item, "reason": f"Fits the {payload['style']} style and leaves room in the budget."})
            total += item["price"]
        if len(selected) >= 6:
            break
    allocation = {"Furniture": round(budget * .40, 2), "Lighting": round(budget * .20, 2), "Decor": round(budget * .25, 2), "Storage": round(budget * .15, 2)}
    return {"summary": f"A {payload['style']} home setup for {', '.join(payload['rooms'])}, keeping the plan under ₹{budget:,.0f}.", "allocation": allocation, "recommendations": selected, "tips": ["Measure the room before buying large furniture.", "Reserve part of the budget for delivery and installation."]}


def fallback_party(payload: dict[str, Any], catalog: list[dict[str, Any]]):
    budget = float(payload["budget"])
    guests = int(payload["guest_count"])
    selected = []
    total = 0
    for item in catalog:
        estimated = item["price"] * guests if item["category"] == "Catering" else item["price"]
        if total + estimated <= budget * .92:
            copy = {**item, "reason": "Selected as a practical option for the event budget."}
            copy["price"] = round(estimated, 2)
            selected.append(copy)
            total += estimated
        if len(selected) >= 5:
            break
    allocation = {"Catering": round(budget * .50, 2), "Decoration": round(budget * .20, 2), "Venue": round(budget * .20, 2), "Entertainment": round(budget * .10, 2)}
    return {"summary": f"A {payload['event_type']} plan for {guests} guests with a ₹{budget:,.0f} budget.", "allocation": allocation, "recommendations": selected, "tips": ["Confirm per-person catering rates before booking.", "Keep a small contingency amount for last-minute needs."]}


